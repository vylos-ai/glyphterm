#!/usr/bin/env node
// Builds the example OBJ models procedurally: node examples/generate.js
// Material names are hex colors, which glyphcss reads directly (no .mtl needed).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

class Mesh {
  constructor() {
    this.lines = [];
    this.vertexCount = 0;
  }

  /** Adds a convex part; faces are wound to point away from `center`. */
  part(material, vertices, faces, center) {
    this.lines.push(`usemtl ${material}`);
    for (const [x, y, z] of vertices) this.lines.push(`v ${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)}`);
    for (const face of faces) {
      const oriented = facesOutward(face.map((i) => vertices[i]), center) ? face : [...face].reverse();
      this.lines.push(`f ${oriented.map((i) => i + 1 + this.vertexCount).join(" ")}`);
    }
    this.vertexCount += vertices.length;
  }

  box(material, [x0, y0, z0], [x1, y1, z1], transform = (v) => v) {
    const corners = [
      [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
      [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
    ].map(transform);
    const faces = [[0, 1, 2, 3], [4, 5, 6, 7], [0, 1, 5, 4], [3, 2, 6, 7], [0, 3, 7, 4], [1, 2, 6, 5]];
    this.part(material, corners, faces, transform([(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2]));
  }

  /** Surface of revolution around the y axis from [radius, y] profile points (bottom to top). */
  lathe(material, profile, segments = 24) {
    const vertices = [];
    for (const [r, y] of profile) {
      for (let s = 0; s < segments; s++) {
        const a = (s / segments) * Math.PI * 2;
        vertices.push([r * Math.cos(a), y, r * Math.sin(a)]);
      }
    }
    const faces = [];
    const ring = (i, s) => i * segments + (s % segments);
    for (let i = 0; i < profile.length - 1; i++) {
      for (let s = 0; s < segments; s++) {
        faces.push([ring(i, s), ring(i, s + 1), ring(i + 1, s + 1), ring(i + 1, s)]);
      }
    }
    const capBottom = profile[0][0] > 0;
    const capTop = profile.at(-1)[0] > 0;
    if (capBottom) faces.push([...Array(segments).keys()].map((s) => ring(0, s)));
    if (capTop) faces.push([...Array(segments).keys()].map((s) => ring(profile.length - 1, s)));
    // Each band is oriented against the axis point at its own height, which works for any profile.
    this.lines.push(`usemtl ${material}`);
    for (const [x, y, z] of vertices) this.lines.push(`v ${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)}`);
    for (const face of faces) {
      const points = face.map((i) => vertices[i]);
      const midY = points.reduce((sum, p) => sum + p[1], 0) / points.length;
      const isCap = face.length === segments;
      const center = isCap ? [0, midY + (midY === profile[0][1] ? 1 : -1), 0] : [0, midY, 0];
      const oriented = facesOutward(points, center) ? face : [...face].reverse();
      this.lines.push(`f ${oriented.map((i) => i + 1 + this.vertexCount).join(" ")}`);
    }
    this.vertexCount += vertices.length;
  }

  /** A tube with `sides` faces swept along a curve in the xy plane. */
  tube(material, points, radius, sides = 6) {
    const rings = points.map((p, i) => {
      const a = points[Math.max(0, i - 1)];
      const b = points[Math.min(points.length - 1, i + 1)];
      const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
      const normal = [-(b[1] - a[1]) / len, (b[0] - a[0]) / len];
      return [...Array(sides).keys()].map((s) => {
        const angle = (s / sides) * Math.PI * 2;
        const [c, d] = [Math.cos(angle) * radius, Math.sin(angle) * radius];
        return [p[0] + normal[0] * c, p[1] + normal[1] * c, p[2] + d];
      });
    });
    this.lines.push(`usemtl ${material}`);
    for (const [x, y, z] of rings.flat()) this.lines.push(`v ${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)}`);
    const index = (i, s) => i * sides + (s % sides);
    for (let i = 0; i < points.length - 1; i++) {
      const center = points[i].map((v, k) => (v + points[i + 1][k]) / 2);
      for (let s = 0; s < sides; s++) {
        const face = [index(i, s), index(i, s + 1), index(i + 1, s + 1), index(i + 1, s)];
        const oriented = facesOutward(face.map((f) => rings.flat()[f]), center) ? face : [...face].reverse();
        this.lines.push(`f ${oriented.map((f) => f + 1 + this.vertexCount).join(" ")}`);
      }
    }
    this.vertexCount += points.length * sides;
  }

  toString() {
    return `# generated by examples/generate.js\n${this.lines.join("\n")}\n`;
  }
}

function facesOutward(points, center) {
  const [a, b, c] = points;
  const u = a.map((v, i) => b[i] - v);
  const w = a.map((v, i) => c[i] - v);
  const normal = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]];
  const centroid = [0, 1, 2].map((i) => points.reduce((sum, p) => sum + p[i], 0) / points.length);
  return normal.reduce((dot, n, i) => dot + n * (centroid[i] - center[i]), 0) >= 0;
}

function retroComputer() {
  const m = new Mesh();
  const BEIGE = "D8CFB4";
  const SHADOW = "B9AF93";
  m.box(BEIGE, [-1, -0.75, -0.9], [1, 0.85, 0.5]); // monitor case
  m.box(SHADOW, [-0.7, -0.55, -1.5], [0.7, 0.6, -0.9]); // CRT back
  m.box("12301C", [-0.82, -0.6, 0.5], [0.82, 0.68, 0.54]); // screen glass
  [0.45, 0.25, 0.05, -0.15].forEach((y, i) => {
    const width = [1.1, 0.7, 1.25, 0.35][i];
    m.box("33FF66", [-0.7, y - 0.06, 0.54], [-0.7 + width, y + 0.04, 0.56]); // lines of text
  });
  m.box("33FF66", [-0.7, -0.42, 0.54], [-0.58, -0.28, 0.57]); // cursor
  m.box(SHADOW, [-0.35, -0.95, -0.6], [0.35, -0.75, 0.2]); // stand
  m.box(BEIGE, [-1.1, -1.12, 0.75], [1.1, -0.98, 1.6]); // keyboard
  for (let row = 0; row < 4; row++) {
    for (let col = 0; col < 11; col++) {
      const x = -1.0 + col * 0.183;
      const z = 0.85 + row * 0.18;
      m.box(row === 3 && col > 2 && col < 8 ? BEIGE : "8C846C", [x, -0.98, z], [x + 0.14, -0.93, z + 0.14]);
    }
  }
  return m;
}

function rocket() {
  const m = new Mesh();
  m.lathe("E8E8E8", [[0.36, -0.9], [0.4, -0.3], [0.4, 0.5], [0.36, 0.8]]); // body
  m.lathe("E0402F", [[0.36, 0.8], [0.3, 1.1], [0.16, 1.35], [0, 1.5]]); // nose cone
  m.lathe("555555", [[0.2, -1.2], [0.28, -1.05], [0.32, -0.9]]); // nozzle
  m.lathe("FFB000", [[0, -1.5], [0.12, -1.35], [0.18, -1.2]], 12); // flame
  for (let i = 0; i < 3; i++) {
    const a = (i / 3) * Math.PI * 2;
    const spin = ([x, y, z]) => [x * Math.cos(a) - z * Math.sin(a), y, x * Math.sin(a) + z * Math.cos(a)];
    m.box("E0402F", [0.35, -1.1, -0.03], [0.85, -0.45, 0.03], spin); // fins
  }
  m.box("3FA9FF", [-0.14, 0.2, 0.36], [0.14, 0.48, 0.44]); // window
  return m;
}

function oscilloscope() {
  const m = new Mesh();
  m.box("081A0E", [-3.2, -1.6, -0.36], [3.2, 1.6, -0.3]); // screen
  for (let x = -3; x <= 3.001; x += 0.5) {
    const axis = Math.abs(x) < 1e-6;
    m.box(axis ? "2E7D45" : "17402A", [x - 0.012, -1.5, -0.3], [x + 0.012, 1.5, -0.28]); // vertical divisions
  }
  for (let y = -1.5; y <= 1.501; y += 0.5) {
    const axis = Math.abs(y) < 1e-6;
    m.box(axis ? "2E7D45" : "17402A", [-3, y - 0.012, -0.3], [3, y + 0.012, -0.28]); // horizontal divisions
  }
  const trace = [];
  for (let i = 0; i <= 300; i++) {
    const x = -3 + (6 * i) / 300;
    trace.push([x, 1.1 * Math.sin(Math.PI * x), 0]); // three full periods
  }
  m.tube("33FF66", trace, 0.05);
  return m;
}

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "computer.obj"), retroComputer().toString());
writeFileSync(join(here, "rocket.obj"), rocket().toString());
writeFileSync(join(here, "oscilloscope.obj"), oscilloscope().toString());
console.log("wrote examples/computer.obj, rocket.obj and oscilloscope.obj");
